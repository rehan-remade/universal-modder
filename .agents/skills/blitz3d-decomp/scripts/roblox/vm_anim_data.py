"""Write a viewmodel's keyframes (b3d_skin.py JSON) as a Luau data module for the Roblox runtime.

Space: the uploaded model is Roblox (-x, y, z) of Blitz times --scale (the FBX path turns it 180 deg
about Y; checked on one viewmodel: Bone Base at (-0.206, -0.19, 0.64) = Blitz (3.433, -3.192, 10.692) * 0.06).
So every Blitz local matrix M becomes D M D with D = diag(-1, 1, 1), and Blitz applies the conjugate of
its stored quaternion (vm_build.py).

Module layout (all local transforms, parent-relative, model space, studs):
  Nodes = { {name, parent index (0 = mesh root), restPos {x,y,z}, restQuat {x,y,z,w}, flags}, ... }
  Frames = first..last, Fps, Seqs = { name = {first, last} }
  Blob = base64 of little-endian int16: for each node, for each frame (or one frame if the node never
         moves): px, py, pz (x POS_Q), qx, qy, qz, qw (x 32767)

Usage:
  python -I vm_anim_data.py IN.json OUT.luau --scale 0.06 --name NAME
"""
import argparse
import base64
import json
import math
import struct

POS_Q = 16000.0


def quat_mul(a, b):
    aw, ax, ay, az = a
    bw, bx, by, bz = b
    return (aw * bw - ax * bx - ay * by - az * bz, aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx, aw * bz + ax * by - ay * bx + az * bw)


def convert(pos, rot, scale):
    # Blitz applies conj(q) = (w, -x, -y, -z). Conjugating a rotation by D = diag(-1, 1, 1) maps the
    # quaternion (w, x, y, z) to (w, x, -y, -z).
    w, x, y, z = rot
    cw, cx, cy, cz = w, -x, -y, -z
    q = (cw, cx, -cy, -cz)
    n = math.sqrt(sum(c * c for c in q))
    q = tuple(c / n for c in q)
    if q[0] < 0:
        q = tuple(-c for c in q)
    p = (-pos[0] * scale, pos[1] * scale, pos[2] * scale)
    return p, q


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("dst")
    ap.add_argument("--scale", type=float, required=True)
    ap.add_argument("--name", required=True)
    a = ap.parse_args()
    data = json.load(open(a.src, encoding="utf-8"))
    root = data["root"]
    seqs = root.get("seqs", [])
    first = min(s["first"] for s in seqs)
    last = max(s["last"] for s in seqs)

    nodes, seen = [], {}

    def collect(n, parent_index):
        name = n["name"]
        if name in seen:
            seen[name] += 1
            name = "%s_%d" % (name, seen[name])
        else:
            seen[name] = 0
        index = len(nodes) + 1 if n is not root else 0
        if n is not root:
            nodes.append((n, name, parent_index))
        for c in n["children"]:
            collect(c, index)

    collect(root, 0)

    blob = bytearray()
    rows = []
    for n, name, parent in nodes:
        keys = {k["frame"]: k for k in n.get("keys", [])}
        frames = []
        cur_pos, cur_rot = n["pos"], n["rot"]
        for f in range(first, last + 1):
            k = keys.get(f)
            if k:
                cur_pos, cur_rot = k.get("pos", cur_pos), k.get("rot", cur_rot)
            frames.append(convert(cur_pos, cur_rot, a.scale))
        # keep quaternion signs continuous so interpolation takes the short way
        for i in range(1, len(frames)):
            p, q = frames[i]
            if sum(x * y for x, y in zip(q, frames[i - 1][1])) < 0:
                frames[i] = (p, tuple(-c for c in q))
        static = all(max(abs(x - y) for x, y in zip(fr[0] + fr[1], frames[0][0] + frames[0][1])) < 1e-6 for fr in frames)
        use = frames[:1] if static else frames
        for p, q in use:
            w, x, y, z = q
            vals = [round(c * POS_Q) for c in p] + [round(c * 32767) for c in (x, y, z, w)]
            assert all(-32768 <= v <= 32767 for v in vals), (name, vals)
            blob += struct.pack("<7h", *vals)
        rp, rq = convert(n["pos"], n["rot"], a.scale)
        rows.append('\t{ "%s", %d, { %.6f, %.6f, %.6f }, { %.6f, %.6f, %.6f, %.6f }, %s },'
                    % (name, parent, rp[0], rp[1], rp[2], rq[1], rq[2], rq[3], rq[0], "true" if static else "false"))

    b64 = base64.b64encode(bytes(blob)).decode("ascii")
    lines = ["-- GENERATED by vm_anim_data.py from the %s model's keyframes; keep the model's credit and licence with it." % a.name,
             "-- Do not edit: re-run the tool. Layout and spaces: see the tool's docstring.",
             "return {",
             "\tName = %s," % json.dumps(a.name),
             "\tScale = %s," % a.scale,
             "\tFps = %s," % root.get("anim", {}).get("fps", 20),
             "\tFirst = %d," % first, "\tLast = %d," % last, "\tPosQ = %s," % POS_Q,
             "\tSeqs = {"]
    for s in seqs:
        lines.append("\t\t%s = { %d, %d }," % (s["name"], s["first"], s["last"]))
    lines += ["\t},", "\t-- { name, parent (0 = mesh root), rest pos, rest quat {x, y, z, w}, static }", "\tNodes = {"]
    lines += ["\t" + r for r in rows]
    lines += ["\t},", '\tBlob = "%s",' % b64, "}", ""]
    open(a.dst, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(json.dumps({"nodes": len(nodes), "static": sum(1 for r in rows if r.endswith("true },")),
                      "bytes": len(blob), "luau_chars": sum(len(l) + 1 for l in lines)}))


if __name__ == "__main__":
    main()
